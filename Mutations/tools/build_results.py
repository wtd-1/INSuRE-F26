"""Assemble Mutations/results.csv and Mutations/RESULTS.md from the variant runs.

Usage: python3 build_results.py

One CSV row per (variant, goal), all 16 goals per variant; `in_family` marks
the eight goals the variant is scored on. Suspect flags follow the reporting
rules in README.md:

  HOLDS_BUT_PREDICTED_VIOLATED  a goal we expected to break reports HOLDS
  NO_PEER_STRAND                the search tree never added the peer role
  PARAMS_DISAGREE               tight and default runs give different verdicts
  INCOMPLETE                    no counterexample and the search did not finish
  PREDICTION_MISMATCH           any other disagreement with the prediction
"""
import csv, hashlib, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
MUT = os.path.dirname(HERE)
ORDER = ["m0", "m1", "m2", "m3", "m3c", "m3s", "m4", "m4c", "m5", "m6", "m7", "m8"]
FAMILY = {v: ("M" if v in ("m5", "m6", "m7", "m8") else "S") for v in ORDER}


def sha256(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def read_csv(p):
    return {r["goal"]: r for r in csv.DictReader(open(p))}


def timings(d):
    out = {}
    for line in open(os.path.join(d, "timings.txt")):
        f = dict(x.split("=", 1) for x in line.strip().split("\t")[1:])
        out[line.split("\t")[0]] = f
    return out


rows = []
for v in ORDER:
    d = os.path.join(MUT, v)
    pred, tight, dflt = (read_csv(os.path.join(d, n)) for n in
                         ("predictions.csv", "goals_tight.csv", "goals_default.csv"))
    tm = timings(d)
    for g, p in pred.items():
        t, df = tight[g], dflt[g]
        reasons = []
        if t["verdict"] != df["verdict"]:
            reasons.append("PARAMS_DISAGREE")
        for r in (t, df):
            if r["verdict"] == "HOLDS" and p["predicted"] == "VIOLATED":
                reasons.append("HOLDS_BUT_PREDICTED_VIOLATED")
            if r["peer_strand_added"] == "False":
                reasons.append("NO_PEER_STRAND")
            if r["verdict"] == "INCOMPLETE":
                reasons.append("INCOMPLETE")
        if df["verdict"] in ("HOLDS", "VIOLATED") and df["verdict"] != p["predicted"]:
            reasons.append("PREDICTION_MISMATCH")
        if df["verdict"] == "ERROR":
            reasons = ["CPSA_REJECTED_INPUT"]
        reasons = sorted(set(reasons))
        rows.append({
            "variant": v, "family": FAMILY[v], "goal": g, "goal_name": df["name"],
            "in_family": g[0] == FAMILY[v],
            "predicted": p["predicted"],
            "verdict_tight": t["verdict"], "verdict_default": df["verdict"],
            "search_complete_tight": t["search_complete"],
            "search_complete_default": df["search_complete"],
            "skeletons_tight": t["skeletons"], "shapes_tight": t["shapes"],
            "skeletons_default": df["skeletons"], "shapes_default": df["shapes"],
            "run_seconds_tight": tm["tight"]["seconds"],
            "run_seconds_default": tm["default"]["seconds"],
            "peer_strand_added_default": df["peer_strand_added"],
            "flags": ";".join(reasons),
            "cpsa_version": tm["default"]["cpsa"],
            "macros_sha256": sha256(os.path.join(d, "TLS1.3_macros.lisp")),
            "scm_sha256": sha256(os.path.join(d, "tls13_baseline.scm")),
        })

with open(os.path.join(MUT, "results.csv"), "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)

# Human-readable grid: in-family goals only.
SYM = {"HOLDS": "H", "VIOLATED": "V", "INCOMPLETE": "?", "NOT_RUN": "-", "ERROR": "E"}
md = ["# Results (generated by tools/build_results.py; do not edit)", "",
      "Cell = default-run verdict. H holds, V violated, ? incomplete (no counterexample, search cut off).",
      "`!` = differs from the sealed prediction. `~` = tight and default runs disagree.",
      "`n` = search tree never added a peer strand.", ""]
for fam, goals in (("S", [f"S{i}" for i in range(1, 9)]), ("M", [f"M{i}" for i in range(1, 9)])):
    md.append(f"## {'Server-only' if fam == 'S' else 'Mutual'} authentication family")
    md.append("")
    md.append("| variant | " + " | ".join(goals) + " | run s (tight / default) |")
    md.append("|---|" + "---|" * len(goals) + "---|")
    for v in ORDER:
        if FAMILY[v] != fam:
            continue
        cells = []
        for g in goals:
            r = next(x for x in rows if x["variant"] == v and x["goal"] == g)
            c = SYM[r["verdict_default"]]
            if "PREDICTION_MISMATCH" in r["flags"] or "HOLDS_BUT_PREDICTED_VIOLATED" in r["flags"]:
                c += "!"
            if "PARAMS_DISAGREE" in r["flags"]:
                c += "~"
            if "NO_PEER_STRAND" in r["flags"]:
                c += "n"
            cells.append(c)
        r0 = next(x for x in rows if x["variant"] == v)
        md.append(f"| {v} | " + " | ".join(cells) +
                  f" | {float(r0['run_seconds_tight']):.1f} / {float(r0['run_seconds_default']):.1f} |")
    md.append("")
open(os.path.join(MUT, "RESULTS.md"), "w").write("\n".join(md))
print(f"results.csv: {len(rows)} rows; RESULTS.md written")
