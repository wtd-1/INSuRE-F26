#!/bin/bash
#
# Generate the experiment lists for the paper's whole corpus (Table 4 of
# Rasoamanana, Levillain, Debar, ESORICS 2022) from the tags in stacks/*/tags:
#
#   experiments/paper-full.tsv     the stacks and version ranges of Table 4
#   experiments/extra-stacks.tsv   stacks of this repo that the paper did not use
#
# For each stack version and supported TLS version, servers get a server and a
# srv-auth (mutual authentication) inference, clients a client inference, with
# the tls10 / tls12 / tls13 scenario. TLS 1.0 servers also get bb-oracle
# (Bleichenbacher), TLS 1.0 clients freak.
#
# Usage: experiments/generate-paper-full.sh   (prints a per-stack summary)

set -e
cd "$(dirname "$0")/.."

tags() { ls "stacks/$1/tags" | grep -v '^tags-list$'; }

ver_le() {  # $1 <= $2, version order
    [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n1)" = "$1" ]
}
in_range() {  # $2 <= $1 <= $3
    ver_le "$2" "$1" && ver_le "$1" "$3"
}

scenario_of() {
    case "$1" in 1.0) echo tls10 ;; 1.2) echo tls12 ;; 1.3) echo tls13 ;; esac
}

COUNTS="$(mktemp)"
trap 'rm -f "$COUNTS"' EXIT

# emit <label> <role: server|client|both> <image> <tls versions...>
emit() {
    local label="$1" role="$2" image="$3" v rows=0
    shift 3
    for v in "$@"; do
        s="$(scenario_of "$v")"
        if [ "$role" != client ]; then
            printf 'server\t%s\t%s\t%s\n' "$image" "$v" "$s"
            printf 'srv-auth\t%s\t%s\t%s\n' "$image" "$v" "$s"
            rows=$((rows + 2))
            if [ "$v" = 1.0 ]; then
                printf 'server\t%s\t1.0\tbb-oracle\n' "$image"
                rows=$((rows + 1))
            fi
        fi
        if [ "$role" != server ]; then
            printf 'client\t%s\t%s\t%s\n' "$image" "$v" "$s"
            rows=$((rows + 1))
            if [ "$v" = 1.0 ]; then
                printf 'client\t%s\t1.0\tfreak\n' "$image"
                rows=$((rows + 1))
            fi
        fi
    done
    printf '%s\t%s\n' "$label" "$rows" >> "$COUNTS"
}

# ---------------------------------------------------------------------------
# Version rules (Table 4 of the paper)
# ---------------------------------------------------------------------------

openssl_versions() {  # tag -> supported TLS versions (empty: excluded)
    case "$1" in
        OpenSSL_0_9_8*|OpenSSL_1_0_0*) echo 1.0 ;;
        OpenSSL_1_0_1d) ;;  # excluded by the paper: defective CBC implementation
        OpenSSL_1_0_1) ;;   # the paper's range starts at 1.0.1a
        OpenSSL_1_0_1*|OpenSSL_1_0_2*|OpenSSL_1_1_0*) echo 1.0 1.2 ;;
        OpenSSL_1_1_1*|openssl-3.0.*) echo 1.0 1.2 1.3 ;;
    esac
}

wolfssl_versions() {  # tag [upper bound] -> supported TLS versions
    local v="${1#v}"
    v="${v%-stable}"
    [ "$1" = v3.69.d ] && return 0  # odd tag, not a 3.x release
    if in_range "$v" 3.12.0 3.14.4; then
        echo 1.0 1.2
    elif in_range "$v" 3.15.5 "${2:-5.2.0}"; then
        echo 1.0 1.2 1.3
    fi
}

nss_versions() {  # NSS_3_39_RTM -> 3.39
    local v
    v="$(echo "$1" | sed -e 's/^NSS_//' -e 's/_RTM$//' -e 's/_/./g')"
    if ver_le "$v" 3.38.99; then echo 1.0 1.2; else echo 1.0 1.2 1.3; fi
}

generate_paper() {
    echo "# The paper's corpus (Table 4), generated by experiments/generate-paper-full.sh."
    echo "# kind  image  tls_version  scenario  [extra pylstar-tls arguments]"

    echo; echo "# OpenSSL (s_server / s_client)"
    for d in openssl-git--0_9_8 openssl-git--1_0 openssl-git--1_1--3_0; do
        for t in $(tags $d | sort -V); do
            vs="$(openssl_versions "$t")"
            [ -n "$vs" ] && emit "OpenSSL $t" both "openssl:$t" $vs
        done
    done

    echo; echo "# curl+OpenSSL (client only)"
    for d in openssl-git--1_0 openssl-git--1_1--3_0; do
        for t in $(tags $d | sort -V); do
            vs="$(openssl_versions "$t")"
            [ -n "$vs" ] && emit "curl+OpenSSL $t" client "curl-openssl:$t" $vs
        done
    done

    echo; echo "# GnuTLS and curl+GnuTLS"
    for t in $(tags gnutls-git | sort -V); do
        emit "GnuTLS $t" both "gnutls:$t" 1.0 1.2 1.3
        emit "curl+GnuTLS $t" client "curl-gnutls:$t" 1.0 1.2 1.3
    done

    echo; echo "# mbedTLS (1.3.10-1.4: TLS 1.0 only; 2.0.0-3.0.0p1: TLS 1.0 and 1.2)"
    for t in $(tags mbedtls-git | sort -V); do
        case "$t" in
            mbedtls-1.*) emit "mbedTLS $t" both "mbedtls:$t" 1.0 ;;
            *)           emit "mbedTLS $t" both "mbedtls:$t" 1.0 1.2 ;;
        esac
    done

    echo; echo "# wolfSSL (3.12.0-3.14.4: TLS 1.0 and 1.2; 3.15.5-5.2.0: all) and curl+wolfSSL (up to 5.1.1)"
    for t in $(tags wolfssl-git | sort -V); do
        vs="$(wolfssl_versions "$t")"
        [ -n "$vs" ] && emit "wolfSSL $t" both "wolfssl:$t" $vs
        vs="$(wolfssl_versions "$t" 5.1.1)"
        [ -n "$vs" ] && emit "curl+wolfSSL $t" client "curl-wolfssl:$t" $vs
    done

    echo; echo "# MatrixSSL (servers)"
    emit "MatrixSSL 3.7.2" server "matrixssl:3.7.2" 1.0
    echo "# MatrixSSL 4.0.0-4.3.0 cannot be built: github.com/matrixssl/matrixssl no longer exists."
    for t in 4-0-0-open 4-0-1-open 4-0-2-open 4-1-0-open 4-2-1-open 4-2-2-open 4-3-0-open; do
        emit "MatrixSSL-4.x(unbuildable) $t" server "matrixssl:$t" 1.0 1.2 1.3 | sed 's/^/# /'
    done

    echo; echo "# NSS (3.15-3.38: TLS 1.0 and 1.2; 3.39-3.78: all)"
    for d in nss-git--3_15 nss-git--3_16_17 nss-git--3_18_20 nss-git--3_21_36 nss-git; do
        for t in $(tags $d | sort -V); do
            emit "NSS $t" both "nss:$t" $(nss_versions "$t")
        done
    done

    echo; echo "# Erlang (servers; OTP 20: TLS 1.0 only)"
    emit "Erlang OTP-20.0" server "erlang:OTP-20.0" 1.0
    for t in $(tags erlang-24-git | sort -V); do
        emit "Erlang $t" server "erlang:$t" 1.0 1.2 1.3
    done

    echo; echo "# fizz (TLS 1.3 clients, weekly snapshots 2021.02-2021.06)"
    for t in $(tags fizz-git | grep -E '^v2021\.0[2-6]\.' | sort -V); do
        emit "fizz $t" client "fizz:$t" 1.3
    done
}

generate_extra() {
    echo "# Stacks of this repo that the paper did not use, generated by experiments/generate-paper-full.sh."
    echo "# kind  image  tls_version  scenario  [extra pylstar-tls arguments]"
    echo; echo "# BoringSSL"
    for t in $(tags boringssl-git | sort -V); do
        emit "BoringSSL $t" both "boringssl:$t" 1.0 1.2 1.3
    done
    echo; echo "# PicoTLS (TLS 1.3 clients)"
    for t in $(tags picotls-git | sort -V); do
        emit "PicoTLS $t" client "picotls:$t" 1.3
    done
    echo; echo "# mbedTLS with a deliberately vulnerable patch (stacks/mbedtls-vulnerable)"
    emit "mbedTLS-vulnerable vulnerable" server "mbedtls:vulnerable" 1.0 1.2
}

generate_paper > experiments/paper-full.tsv
generate_extra > experiments/extra-stacks.tsv

# Per-family summary (versions, runs) to compare with Table 4.
echo "Versions per stack family (compare with Table 4 of the paper):"
sed -e 's/ [^ ]*\t/\t/' "$COUNTS" | cut -f1 | sort | uniq -c | while read -r n label; do
    printf '  %-30s %3s\n' "$label" "$n"
done
echo "paper-full.tsv: $(grep -vc '^#\|^$' experiments/paper-full.tsv) lines; extra-stacks.tsv: $(grep -vc '^#\|^$' experiments/extra-stacks.tsv) lines"
